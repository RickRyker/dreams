// tools/generate-shared-index.cjs
const fs = require("fs");
const path = require("path");

const SHARED = path.resolve(__dirname, "../shared");
const OUT = path.join(SHARED, "index.ts");

function listTsFiles(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".ts") && f.toLowerCase() !== "index.ts")
    .map((f) => f.replace(/\.ts$/, ""));
}

function writeSection(title, files, folder) {
  if (files.length === 0) return "";
  let out = `\n// --------------------\n// ${title}\n// --------------------\n`;
  for (const f of files.sort()) {
    out += `export * from "./${folder}/${f}";\n`;
  }
  return out;
}

function main() {
  let out = `//\n// AUTO-GENERATED FILE — DO NOT EDIT\n// Generated by tools/generate-shared-index.cjs\n//\n`;

  out += writeSection("DTO", listTsFiles(path.join(SHARED, "dto")), "dto");
  out += writeSection("Mappers", listTsFiles(path.join(SHARED, "mappers")), "mappers");
  out += writeSection("Replay", listTsFiles(path.join(SHARED, "replay")), "replay");
  out += writeSection("Services", listTsFiles(path.join(SHARED, "services")), "services");
  out += writeSection("Types", listTsFiles(path.join(SHARED, "types")), "types");
  out += writeSection("Zod", listTsFiles(path.join(SHARED, "zod")), "zod");

  fs.writeFileSync(OUT, out.trim() + "\n", "utf8");
  console.log("Generated shared/index.ts");
}

main();
